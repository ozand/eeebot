def supported_hypotheses(state_dir: Path, n: int = SUPPORTED_TOP_N) -> list[dict[str, Any]]:
    """Hypotheses the harness-computed verdict (:mod:`hypothesis_verdict`)
    marked ``"supported"`` — newest ``verdict_at`` first, capped to ``n``.

    Each item is ``{"title": ..., "evidence": ...}`` where ``evidence`` is
    the SAME ``verdict_evidence`` dict persisted on the lifecycle entry
    (already sourced from a measured sidecar, never instance-authored
    text). Consumed by ``goal_review._collect_evidence`` as an additional
    citable evidence line, the same way decay/goal-gap evidence already is
    — a supported hypothesis still has to pass ``goal_review``'s normal
    fail-closed ``validate_priority`` before it can ever become a priority.
    Fail-open: ``[]`` on any error or when nothing is verdict-marked yet."""
    try:
        state_dir = Path(state_dir)
        lifecycle = _load_lifecycle(state_dir)
        entries = lifecycle.get("entries", {})
        if not isinstance(entries, dict):
            return []
        ranked: list[tuple[str, dict[str, Any]]] = []
        for entry in entries.values():
            if not isinstance(entry, dict):
                continue
            if entry.get("orphaned"):
                continue  # #1346: a fossil's verdict is not current evidence
            if str(entry.get("verdict") or "") != "supported":
                continue
            title = str(entry.get("title") or "").strip()
            if not title:
                continue
            ranked.append(
                (str(entry.get("verdict_at") or ""), {"title": title, "evidence": entry.get("verdict_evidence") or {}})
            )
        ranked.sort(key=lambda pair: pair[0], reverse=True)
        return [item for _, item in ranked[:n]]
    except Exception:
        return []


def lifecycle_counts(state_dir: Path) -> dict[str, int]:
    """Counts over every lifecycle entry — read by
    ``scorecard._control_plane_snapshot`` and the dashboard for VISIBILITY
    ONLY, never fed into fitness/targets/gaps. Fail-open to ``{}``.

    #878: ``active``/``answered`` (``status``) and
    ``supported``/``refuted``/``inconclusive`` (``verdict``) are independent
    fields, so an answered entry contributes to both.

    #1346 (additive): ``total``, ``stale``, ``orphaned`` (rows whose key was
    absent from every input at the last pass — never deleted, never
    evaluated), ``evaluated_last_pass`` (rows present in the inputs at the
    last pass), ``id_keyed`` / ``slug_keyed`` (rows keyed by ``hypothesis_id``
    vs the title-slug fallback — the slug count is the direct measure of the
    rename problem), ``claim_keyed`` (rows carrying a #1345 claim key) and
    ``claim_collisions`` (rows beyond the first per claim key — restatements
    of one idea under several keys), ``inputs_unavailable`` (sources that
    could not be read at the last pass; when > 0 no orphan marks were made),
    ``last_pass_recorded`` (0 until a #1346 pass has run — then ``orphaned`` and
    ``evaluated_last_pass`` are unmeasured, not zero; a corrupt sidecar
    returns ``{}``), ``input_id_collisions`` (input entries sharing a ``hypothesis_id`` with
    another entry at the last pass — several hypotheses behind one row),
    and the key-prefix breakdown ``prefix_hypothesis`` (``hypothesis-*``, the
    ids of the planner retired in #923 — 91 of the 115 live rows on
    2026-09-05), ``prefix_hyp`` (``hyp-*``, the strategist's durable ids),
    ``prefix_slug`` (``slug-*``), ``prefix_other``.
    """
    try:
        state_dir = Path(state_dir)
        lifecycle, status = _load_lifecycle_status(state_dir)
        if status == "corrupt":
            return {}  # no data is not zero of everything
        entries = lifecycle.get("entries", {})
        if not isinstance(entries, dict):
            return {}
        counts = {
            "active": 0, "answered": 0, "supported": 0, "refuted": 0, "inconclusive": 0,
            "total": 0, "stale": 0, "orphaned": 0, "evaluated_last_pass": 0,
            "id_keyed": 0, "slug_keyed": 0, "claim_keyed": 0, "claim_collisions": 0,
            "inputs_unavailable": 0, "input_id_collisions": 0,
            "prefix_hypothesis": 0, "prefix_hyp": 0, "prefix_slug": 0, "prefix_other": 0,
            # 1 once a #1346 pass has run; 0 means orphaned/evaluated_last_pass
            # are "not yet measured", not "measured zero"
            "last_pass_recorded": 0,
        }
        last_pass = lifecycle.get("last_pass") if isinstance(lifecycle.get("last_pass"), dict) else {}
        counts["last_pass_recorded"] = 1 if last_pass.get("at") else 0
        last_at = str(last_pass.get("at") or "")
        inputs = last_pass.get("inputs") if isinstance(last_pass.get("inputs"), dict) else {}
        counts["inputs_unavailable"] = sum(1 for v in inputs.values() if v != "ok")
        counts["input_id_collisions"] = int(last_pass.get("input_id_collisions") or 0)
        claims: dict[str, int] = {}
        for key, entry in entries.items():
            if not isinstance(entry, dict):
                continue
            counts["total"] += 1
            status = str(entry.get("status") or "")
            if status in ("active", "answered", "stale"):
                counts[status] += 1
            verdict = str(entry.get("verdict") or "")
            if verdict in ("supported", "refuted", "inconclusive"):
                counts[verdict] += 1
            if entry.get("orphaned"):
                counts["orphaned"] += 1
            if last_at and str(entry.get("last_evaluated") or "") == last_at:
                counts["evaluated_last_pass"] += 1
            if str(key).startswith("slug-"):
                counts["slug_keyed"] += 1
            else:
                counts["id_keyed"] += 1
            prefix = str(key).split("-", 1)[0]
            counts["prefix_" + (prefix if prefix in ("hypothesis", "hyp", "slug") else "other")] += 1
            claim = str(entry.get("claim_key") or "")
            if claim:
                counts["claim_keyed"] += 1
                claims[claim] = claims.get(claim, 0) + 1
        counts["claim_collisions"] = sum(n - 1 for n in claims.values() if n > 1)
        return counts
    except Exception:
        return {}


def has_in_flight_experiment(
    state_dir: Path,
    *,
    now: datetime | None = None,
    ledger_rows: list[dict[str, Any]] | None = None,
) -> bool:
    """True iff some ``active``-status hypothesis candidate has a
    ``'proposed'`` ledger row (``serves: hypothesis <ref>``) whose
    ``cycle_id`` has NOT YET produced a terminal ``'outcome'`` row AND whose
    ``proposed`` row is younger than :data:`IN_FLIGHT_TIMEOUT_DAYS` — i.e.
    an experiment cycle for it is currently running or awaiting its
    verdict.

    Used by ``demand._hypothesis_items`` to enforce the #878 "at most one
    active hypothesis experiment" rule: while this is true, no NEW
    hypothesis-kind demand item is minted this cycle (the loop keeps
    presenting whatever else it has instead of stacking a second parallel
    experiment on top of the one already running). Deliberately does not
    consult ``exhausted``/``completed`` state — this is only about a cycle
    that is currently open, not about retry bookkeeping.

    #878 opus-review Y1 fix: a serving cycle that crashed on the host
    (power loss, OOM-kill, process kill) never writes a terminal
    ``'outcome'`` row at all — without a timeout this would read as
    permanently in-flight, freezing the whole hypothesis demand lane until
    the candidate separately ages into :data:`STALE_AFTER_DAYS` (14 days).
    A ``'proposed'`` row older than :data:`IN_FLIGHT_TIMEOUT_DAYS` is
    therefore treated as abandoned, not still-running, regardless of
    whether it ever gets an outcome — a row with a missing/unparseable
    ``ts`` is conservatively still counted as in-flight (cannot confirm
    it's timed out). Fail-open: ``False`` on any error (never blocks demand
    collection); ``True`` on a ``partial``/``unavailable`` ledger window
    (#1175: a rotated-out serving row must not mint a second experiment)."""
    try:
        state_dir = Path(state_dir)
        now = now or datetime.now(timezone.utc)
        candidates = _all_candidates(state_dir)
        if not candidates:
            return False
        lifecycle = _load_lifecycle(state_dir)
        entries = lifecycle.get("entries", {})
        active_keys = {
            cand["key"]
            for cand in candidates
            if str((entries.get(cand["key"]) or {}).get("status") or "active") == "active"
        }
        if not active_keys:
            return False

        if ledger_rows is not None:
            rows = ledger_rows
            # demand.LedgerRows carries the window's evidence status; a plain
            # list (older callers, test doubles) reads as complete.
            ledger_status = str(getattr(ledger_rows, "status", "complete") or "complete")
        else:
            from nanobot.runtime.state_access import evidence_status

            window = _ledger_window(state_dir)
            rows, ledger_status = list(window.rows), evidence_status(window)
        if ledger_status != "complete":
            # #1175: a serving row that rotated out of view, or a ledger that
            # cannot be read, must not mint a second experiment. Assume
            # in-flight; the lane reopens on the next complete read.
            return True
        outcome_cycle_ids: set[str] = set()
        proposed_cycle_ts: dict[str, datetime | None] = {}
        for row in rows:
            cid = row.get("cycle_id")
            if not cid:
                continue
            phase = row.get("phase")
            if phase == "outcome":
                outcome_cycle_ids.add(cid)
                continue
            if phase != "proposed":
                continue
            ref = _serves_hypothesis_ref(str(row.get("serves") or ""))
            if not ref:
                continue
            for cand in candidates:
                if cand["key"] in active_keys and _ref_matches_candidate(ref, cand):
                    proposed_cycle_ts[cid] = _parse_ts(row.get("ts"))
                    break

        for cid, prow_ts in proposed_cycle_ts.items():
            if cid in outcome_cycle_ids:
                continue
            if prow_ts is not None:
                age_days = (now - prow_ts).total_seconds() / 86400.0
                if age_days >= IN_FLIGHT_TIMEOUT_DAYS:
                    continue  # abandoned — no longer counts as in-flight
            return True
        return False
    except Exception:
        return False


def append_hypotheses(state_dir: Path | str, new_entries: list[dict[str, Any]]) -> int:
    """Append structured hypothesis entries to ``state_dir/hypotheses/durable.json`` (#999).

    This is the writer of ``durable.json`` — the strategist's daily run
    (``strategist.run_strategist``) calls it, which is why the file's mtime
    moves once a day at 00:00 UTC. The docstring used to say ``backlog.json``
    (the bridge's per-cycle snapshot, a different file) and #1222 spent a
    row hunting for an out-of-repo writer that was this function all along.

    Preserves the existing schema (dict with schema, updated_at, entries).
    Writes atomically via tempfile + os.replace.
    Returns the number of valid entries actually appended.
    """
    state_dir = Path(state_dir)
    hypotheses_dir = state_dir / "hypotheses"
    hypotheses_dir.mkdir(parents=True, exist_ok=True)
    backlog_path = hypotheses_dir / "durable.json"

    raw_data = _read_json(backlog_path, None)
    if isinstance(raw_data, dict) and isinstance(raw_data.get("entries"), list):
        backlog_data = dict(raw_data)
        entries = list(backlog_data.get("entries") or [])
    else:
        backlog_data = {"schema": "hypothesis-durable-v1", "entries": []}
        entries = []

    # Repair duplicate FIFO-era ids before exact identity links can act on
    # them. Unique legacy ids stay unchanged; each duplicate receives the
    # same content identity used for new entries. Lifecycle rows under the old
    # id remain historical rather than being guessed onto one duplicate.
    id_counts: dict[str, int] = {}
    for entry in entries:
        if isinstance(entry, dict):
            hypothesis_id = str(entry.get("hypothesis_id") or "").strip()
            if hypothesis_id:
                id_counts[hypothesis_id] = id_counts.get(hypothesis_id, 0) + 1
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        hypothesis_id = str(entry.get("hypothesis_id") or "").strip()
        if id_counts.get(hypothesis_id, 0) <= 1:
            continue
        title = str(entry.get("title") or entry.get("task_title") or "").strip()
        hypothesis_text = str(entry.get("hypothesis") or "").strip()
        entry["hypothesis_id"] = "hyp-" + hashlib.sha256(
            f"{title}\n{hypothesis_text}".encode("utf-8")
        ).hexdigest()[:16]

    # Map existing titles / keys to avoid duplicate additions
    # Cheap first pass: exact title dedup
    # Second pass: deterministic claim identity key
    title_to_entry: dict[str, dict[str, Any]] = {}
    claim_to_entry: dict[str, dict[str, Any]] = {}

    for e in entries:
        if not isinstance(e, dict):
            continue
        t = str(e.get("title") or e.get("task_title") or e.get("hypothesis") or "").strip().lower()
        if t and t not in title_to_entry:
            title_to_entry[t] = e
        ckey = hypothesis_identity_key(e)
        if ckey and ckey not in claim_to_entry:
            claim_to_entry[ckey] = e

    def _priority_score(p: Any) -> float:
        if isinstance(p, (int, float)):
            return float(p)
        p_str = str(p or "").strip().lower()
        mapping = {"high": 1.0, "medium": 0.5, "low": 0.2}
        return mapping.get(p_str, 0.5)

    def _strengthen_entry(target: dict[str, Any], incoming: dict[str, Any]) -> None:
        target["seen_count"] = int(target.get("seen_count") or 1) + 1
        # Raise priority if incoming has higher priority
        p_target = _priority_score(target.get("priority"))
        p_incoming = _priority_score(incoming.get("priority"))
        if p_incoming > p_target:
            target["priority"] = incoming.get("priority")

        # Append unique evidence
        incoming_evidence: list[str] = []
        raw_ev = incoming.get("evidence") or incoming.get("data_to_collect")
        if isinstance(raw_ev, list):
            incoming_evidence = [str(x).strip() for x in raw_ev if str(x).strip()]
        elif isinstance(raw_ev, str) and raw_ev.strip():
            incoming_evidence = [raw_ev.strip()]

        existing_evidence = target.get("evidence")
        if isinstance(existing_evidence, list):
            target_evidence = [str(value).strip() for value in existing_evidence if str(value).strip()]
        elif isinstance(existing_evidence, str) and existing_evidence.strip():
            target_evidence = [existing_evidence.strip()]
        else:
            target_evidence = []

        for ev in incoming_evidence:
            if ev not in target_evidence:
                target_evidence.append(ev)
        # durable-v1 evidence is a string on the live reader path. Preserve
        # that shape while retaining each distinct observation.
        target["evidence"] = "\n".join(target_evidence)

    appended = 0
    updated = False
    now_iso = datetime.now(timezone.utc).isoformat()
    for item in new_entries:
        if not isinstance(item, dict):
            continue
        title = str(item.get("title") or item.get("task_title") or "").strip()
        hypothesis_text = str(item.get("hypothesis") or "").strip()
        if not title and not hypothesis_text:
            continue

        lookup_key = (title or hypothesis_text).lower()
        matched_target: dict[str, Any] | None = None

        if lookup_key in title_to_entry:
            matched_target = title_to_entry[lookup_key]
        else:
            item_ckey = hypothesis_identity_key(item)
            if item_ckey in claim_to_entry:
                matched_target = claim_to_entry[item_ckey]

        if matched_target is not None:
            _strengthen_entry(matched_target, item)
            updated = True
            try:
                from nanobot.runtime.cycle_ledger import append_event

                append_event(
                    state_dir,
                    {
                        "phase": "hypothesis",
                        "reason": "claim_collision",
                        "existing_hypothesis_id": str(matched_target.get("hypothesis_id") or ""),
                        "incoming_hypothesis_id": str(item.get("hypothesis_id") or ""),
                    },
                )
            except Exception:
                pass
            continue

        hypothesis_id = str(item.get("hypothesis_id") or "").strip()
        if not hypothesis_id:
            hypothesis_id = "hyp-" + hashlib.sha256(
                f"{title}\n{hypothesis_text}".encode("utf-8")
            ).hexdigest()[:16]

        entry_record: dict[str, Any] = {
            "hypothesis_id": hypothesis_id,
            "task_title": title or hypothesis_text[:80],
            "title": title or hypothesis_text[:80],
            "hypothesis": hypothesis_text,
            "action": str(item.get("action") or "").strip(),
            "data_to_collect": str(item.get("data_to_collect") or "").strip(),
            "insight_criterion": str(item.get("insight_criterion") or "").strip(),
            "evidence": "\n".join(
                str(value).strip()
                for value in (
                    item.get("evidence")
                    if isinstance(item.get("evidence"), list)
                    else [item.get("evidence") or item.get("data_to_collect")]
                )
                if str(value).strip()
            ),
            "priority": item.get("priority", "medium"),
            "seen_count": 1,
            "source": str(item.get("source") or "strategist"),
            "created_at": str(item.get("created_at") or now_iso),
        }
        entries.append(entry_record)
        if lookup_key:
            title_to_entry[lookup_key] = entry_record
        item_ckey = hypothesis_identity_key(entry_record)
        if item_ckey:
            claim_to_entry[item_ckey] = entry_record
        appended += 1

    trimmed = len(entries) > DURABLE_MAX_ENTRIES
    if trimmed:
        entries = entries[-DURABLE_MAX_ENTRIES:]
        backlog_data["entries"] = entries

    if appended > 0 or updated or trimmed or not new_entries:
        backlog_data["updated_at"] = now_iso
        backlog_data["entries"] = entries

        fd, tmp = tempfile.mkstemp(prefix=".backlog.", dir=str(hypotheses_dir))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                json.dump(backlog_data, fh, indent=2, ensure_ascii=False)
                fh.write("\n")
                fh.flush()
                os.fsync(fh.fileno())
            if os.name != "nt":
                os.chmod(tmp, 0o644)  # mkstemp creates 0600; normalize for non-agent readers (#1096)
            os.replace(tmp, backlog_path)
        finally:
            try:
                os.unlink(tmp)
            except FileNotFoundError:
                pass

    return appended
