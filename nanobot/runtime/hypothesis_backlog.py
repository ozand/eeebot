def _claim_tokens(text: str) -> set[str]:
    """Order-insensitive words used only for the bounded claim taxonomy."""
    tokens = set(re.findall(r"[a-z0-9]+", text.lower().replace("_", " ")))
    aliases = {
        "scripts": "script",
        "validators": "validator",
        "demands": "demand",
        "deduplication": "dedup",
        "rejections": "rejection",
        "commits": "commit",
        "refactors": "refactor",
        "outcomes": "outcome",
    }
    return {aliases.get(token, token) for token in tokens}


def _taxonomy_tag(text: str, taxonomy: list[tuple[str, tuple[frozenset[str], ...]]]) -> str | None:
    tokens = _claim_tokens(text)
    for tag, alternatives in taxonomy:
        if any(required <= tokens for required in alternatives):
            return tag
    return None


def hypothesis_identity_key(entry: dict[str, Any]) -> str:
    """Compute deterministic identity key from problem condition and mechanism target.

    Falls back to normalized title if problem/mechanism cannot be extracted or
    if hypothesis and action fields are empty.
    """
    hypothesis = str(entry.get("hypothesis") or "").strip()
    action = str(entry.get("action") or "").strip()
    title = str(entry.get("title") or entry.get("task_title") or "").strip()

    if not hypothesis or not action:
        return f"title-{_slug(title)}" if title else ""

    problem_tag = _taxonomy_tag(hypothesis, _PROBLEM_PATTERNS)
    mechanism_tag = _taxonomy_tag(action, _MECHANISM_PATTERNS)

    if not problem_tag or not mechanism_tag:
        # If the structured pair does not identify both parts of the claim,
        # preserve the pre-#1345 title identity instead of guessing.
        return f"title-{_slug(title)}" if title else ""
    claim_str = f"{problem_tag}:{mechanism_tag}"

    h = hashlib.sha256(claim_str.encode("utf-8")).hexdigest()[:16]
    return f"claim-{h}"


_HYPOTHESIS_SERVES_RE = re.compile(r"^(?:hypothesis|demand)\s+(.+)$", re.IGNORECASE)


def _read_json(path: Path, default: Any) -> Any:
    try:
        if not path.is_file():
            return default
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default


def _write_json(path: Path, data: Any) -> None:
    """Atomic: temp file in the same directory, then ``os.replace``. #1346 —
    an interrupted plain ``write_text`` truncated the sidecar, the next pass
    fail-opened it to ``{}`` and the rows the change promises never to delete
    were gone."""
    tmp_name: str | None = None
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            "w", encoding="utf-8", dir=path.parent, prefix=f".{path.name}.", suffix=".tmp", delete=False
        ) as fh:
            tmp_name = fh.name
            fh.write(json.dumps(data, indent=2, ensure_ascii=False))
        os.replace(tmp_name, path)
        tmp_name = None
    except Exception:
        pass
    finally:
        if tmp_name:
            try:
                os.unlink(tmp_name)
            except OSError:
                pass


def _ledger_window(state_dir: Path, *, days: int = IN_FLIGHT_TIMEOUT_DAYS):
    """The last ``days`` of ledger rows across the live file and its rotated
    archives (``state_access.ledger_window``, #1175). A ``proposed`` row older
    than :data:`IN_FLIGHT_TIMEOUT_DAYS` is abandoned by definition, so this
    window is the whole horizon the in-flight rule can care about."""
    from nanobot.runtime.state_access import ledger_window

    since = datetime.now(timezone.utc) - timedelta(days=days)
    return ledger_window(Path(state_dir), since_ts=since.isoformat().replace("+00:00", "Z"))


def _load_ledger_rows(state_dir: Path) -> list[dict[str, Any]]:
    return list(_ledger_window(state_dir).rows)


def _parse_ts(value: Any) -> datetime | None:
    if not value or not isinstance(value, str):
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    except Exception:
        return None


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.strip().lower()).strip("-")[:60]


def _candidate_key(entry: dict[str, Any]) -> str:
    """Lifecycle key: ``hypothesis_id`` when present, else ``slug-<title>``.

    #1346: the id is preferred whenever it exists; the slug is the fallback
    whose use is counted (``slug_keyed``) because a restated title mints a
    fresh key. The #1345 claim key is recorded alongside (``claim``), not
    used as the key — see :func:`_candidate_claim`.
    """
    hid = str(entry.get("hypothesis_id") or "").strip()
    if hid:
        return hid
    title = str(entry.get("task_title") or entry.get("title") or "").strip()
    return f"slug-{_slug(title)}" if title else ""


def _candidate_claim(entry: dict[str, Any]) -> str:
    """#1345 claim key (``claim-<hash>``) when the entry's hypothesis/action
    resolve to a problem:mechanism pair, else ``""``.

    Recorded on the lifecycle row, NOT used as its key: (1) it collapses
    every hypothesis sharing a problem:mechanism pair into one row, so one
    ``answered`` would answer them all — right for novelty, wrong for a
    per-hypothesis verdict; (2) the ledger's ``serves: hypothesis <ref>``
    rows and ``hypothesis_ref`` name ids/titles, never claims, so keying by
    claim would break answered-detection for every existing row; (3) it
    falls back to ``title-<slug>`` for entries without hypothesis/action —
    the same rename fragility. Rows sharing a claim are counted
    (``claim_collisions``) as the direct measure of restatement.
    """
    try:
        key = hypothesis_identity_key(entry)
    except Exception:
        return ""
    return key if key.startswith("claim-") else ""


def _source_status(state_dir: Path, name: str) -> tuple[str, list[dict[str, Any]]]:
    """``("ok", entries)`` for a readable source file whose ``entries`` is a
    list (possibly empty), ``("missing", [])`` when there is no file (no
    hypotheses yet — the pre-#1346 no-op), ``("unavailable", [])`` when the
    file exists but is unparseable or wrongly shaped. #1346: absence of a
    key from the inputs can only be asserted when every input was actually
    readable — a source that cannot be read is not evidence that its
    hypotheses are gone.
    """
    path = Path(state_dir) / "hypotheses" / name
    try:
        if not path.is_file():
            return "missing", []
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return "unavailable", []
    entries = data.get("entries") if isinstance(data, dict) else None
    if not isinstance(entries, list):
        return "unavailable", []
    return "ok", [e for e in entries if isinstance(e, dict)]


_INPUT_SOURCES = ("durable.json",)  # #1356: backlog.json retired


def _input_status(state_dir: Path) -> dict[str, str]:
    return {name: _source_status(state_dir, name)[0] for name in _INPUT_SOURCES}


def _durable_candidates(state_dir: Path) -> list[dict[str, str]]:
    data = _read_json(Path(state_dir) / "hypotheses" / "durable.json", None)
    entries = data.get("entries") if isinstance(data, dict) else []
    out = []
    for entry in entries if isinstance(entries, list) else []:
        if isinstance(entry, dict):
            key = _candidate_key(entry)
            title = str(entry.get("task_title") or entry.get("title") or "").strip()
            if key and title:
                out.append({"key": key, "title": title, "source": "durable", "claim": _candidate_claim(entry)})
    return out


def _candidates_from(entries: list[dict[str, Any]], source: str) -> list[dict[str, str]]:
    """Candidate rows (key/title/source/claim) from already-read entries."""
    out: list[dict[str, str]] = []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        key = _candidate_key(entry)
        title = str(entry.get("task_title") or entry.get("title") or "").strip()
        if key and title:
            out.append({"key": key, "title": title, "source": source, "claim": _candidate_claim(entry)})
    return out


def _dedupe_candidates(cands: list[dict[str, str]]) -> list[dict[str, str]]:
    seen: set[str] = set()
    out: list[dict[str, str]] = []
    for cand in cands:
        if cand["key"] in seen:
            continue
        seen.add(cand["key"])
        out.append(cand)
    return out


def _all_candidates(state_dir: Path) -> list[dict[str, str]]:
    return _dedupe_candidates(_durable_candidates(state_dir))


def _read_inputs(state_dir: Path) -> tuple[dict[str, str], list[dict[str, str]], set[str], int]:
    """ONE read per source (#1346 review): ``(status by file, candidates,
    present keys, id collisions)``.

    ``present`` is every key the inputs carry, including entries without a
    title (they are *in* the input, so their row is not orphaned even though
    they are not offered as candidates). Collisions are counted within a
    source.
    """
    statuses: dict[str, str] = {}
    raw: list[dict[str, str]] = []
    present: set[str] = set()
    collisions = 0
    for name in _INPUT_SOURCES:
        status, entries = _source_status(state_dir, name)
        statuses[name] = status
        if status != "ok":
            continue
        keys = [k for k in (_candidate_key(e) for e in entries) if k]
        collisions += len(keys) - len(set(keys))
        present.update(keys)
        raw.extend(_candidates_from(entries, name[: -len(".json")]))
    return statuses, _dedupe_candidates(raw), present, collisions


def _load_lifecycle_status(state_dir: Path) -> tuple[dict[str, Any], str]:
    """``(data, status)`` — ``"ok"``, ``"missing"`` (no file yet: a fresh
    sidecar is legitimate), or ``"corrupt"`` (file present but unreadable or
    mis-shaped: a fresh sidecar would overwrite rows we could not read).
    """
    path = Path(state_dir) / "hypotheses" / "lifecycle.json"
    fresh = {"schema_version": "hypothesis-lifecycle-v1", "entries": {}}
    try:
        if not path.is_file():
            return fresh, "missing"
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return fresh, "corrupt"
    if not isinstance(data, dict) or not isinstance(data.get("entries"), dict):
        return fresh, "corrupt"
    return data, "ok"


def _load_lifecycle(state_dir: Path) -> dict[str, Any]:
    return _load_lifecycle_status(state_dir)[0]


def _save_lifecycle(state_dir: Path, data: dict[str, Any]) -> None:
    _write_json(Path(state_dir) / "hypotheses" / "lifecycle.json", data)


def _serves_hypothesis_ref(serves: str) -> str | None:
    match = _HYPOTHESIS_SERVES_RE.match((serves or "").strip())
    if not match:
        return None
    return match.group(1).strip()


def _apply_verdict(state_dir: Path, entry: dict[str, Any], key: str, cycle_id: str, now_iso: str) -> None:
    """#878: compute + persist the harness-measured verdict on a hypothesis
    entry the instant it is first marked ``answered`` (same reconciliation
    pass, no separate hook). Additive to ``entry`` in place: ``verdict``,
    ``verdict_evidence``, ``verdict_at``. Also appends one
    ``{"phase": "hypothesis", "reason": "verdict", ...}`` ledger row.
    Best-effort — a verdict failure must never break ``reconcile``'s
    existing answered/stale bookkeeping."""
    verdict = None
    evidence: dict[str, Any] = {}
    try:
        from nanobot.runtime.hypothesis_verdict import classify_hypothesis_verdict

        verdict, evidence = classify_hypothesis_verdict(state_dir, cycle_id, entry.get("title") or "")
        entry["verdict"] = verdict
        entry["verdict_evidence"] = evidence
        entry["verdict_at"] = now_iso
    except Exception:
        return
    try:
        from nanobot.runtime.cycle_ledger import append_event

        append_event(
            state_dir,
            {
                "phase": "hypothesis",
                "reason": "verdict",
                "hypothesis_ref": key,
                "verdict": verdict,
                "cycle_id": str(cycle_id),
                "evidence": evidence,
            },
        )
    except Exception:
        pass


def _maybe_upgrade_inconclusive_verdict(
    state_dir: Path, entry: dict[str, Any], key: str, now_iso: str
) -> None:
    """#878 opus-review N1 fix: re-evaluate an already-answered hypothesis's
    verdict on a LATER reconcile pass if it is still ``"inconclusive"`` —
    and, per #894, also if it has NO verdict at all (``None``), which is
    the shape of any ``answered`` entry that predates #878 entirely and so
    never got a first classify pass.

    ``_apply_verdict`` originally only ran once, at the exact moment a
    candidate flips to ``answered`` — day 0. At that instant the
    confirmed-usage source (:func:`hypothesis_verdict._confirmed_usage_verdict`)
    is structurally ALWAYS either absent (no completed entry yet) or still
    inside its confirm window, so without this re-check the "supported once
    later confirmed" and "refuted once the window elapses unconfirmed"
    confirmed-usage branches could never fire in production — only
    microbench ever produced a real (non-inconclusive) verdict. This makes
    them reachable: any reconcile pass over an ``answered`` entry whose
    stored ``verdict`` is still ``"inconclusive"`` re-runs
    :func:`hypothesis_verdict.classify_hypothesis_verdict` against the SAME
    serving ``cycle_id`` (``answered_evidence``); if a measured source now
    resolves to ``supported``/``refuted``, the entry and a
    ``{"phase": "hypothesis", "reason": "verdict"}`` ledger event are
    updated exactly like the original transition. If it is STILL
    inconclusive, nothing is written and no event is appended — a
    steady-state inconclusive entry costs one classify call per reconcile
    pass, not a growing write/event history. Best-effort — a failure here
    must never break the rest of reconciliation."""
    cycle_id = entry.get("answered_evidence")
    if not cycle_id:
        return
    try:
        from nanobot.runtime.hypothesis_verdict import classify_hypothesis_verdict

        verdict, evidence = classify_hypothesis_verdict(state_dir, cycle_id, entry.get("title") or "")
    except Exception:
        return
    if verdict == "inconclusive":
        return  # unchanged — no write, no event
    entry["verdict"] = verdict
    entry["verdict_evidence"] = evidence
    entry["verdict_at"] = now_iso
    try:
        from nanobot.runtime.cycle_ledger import append_event

        append_event(
            state_dir,
            {
                "phase": "hypothesis",
                "reason": "verdict",
                "hypothesis_ref": key,
                "verdict": verdict,
                "cycle_id": str(cycle_id),
                "evidence": evidence,
            },
        )
    except Exception:
        pass


def _ref_matches_candidate(ref: str, cand: dict[str, str]) -> bool:
    ref_low = ref.lower().strip()
    if not ref_low:
        return False
    key_low = cand["key"].lower()
    title_low = cand["title"].lower()
    return ref_low == key_low or ref_low in key_low or ref_low in title_low


def reconcile(state_dir: Path, *, now: datetime | None = None) -> None:
    """Lazy lifecycle reconciliation (#751 design choice — no invasive hook
    into where cycle outcomes are recorded; this runs instead as a side
    effect of every :func:`top_candidates`/:func:`context_section` call, i.e.
    once per proposer cycle via ``llm_proposer.build_context``).

    Marks a candidate ``answered`` (with the resolving ``cycle_id`` as
    evidence) the first time a ledger ``'proposed'`` row whose ``serves``
    names it (``hypothesis <ref>``) is later followed by a same-``cycle_id``
    ``'outcome'`` row with ``outcome == "success"``. Demotes any still-
    ``active`` candidate to ``stale`` once it has gone unreferenced by any
    ``serves: hypothesis ...`` proposal for :data:`STALE_AFTER_UNTOUCHED_CYCLES`
    reconciliation passes, or :data:`STALE_AFTER_DAYS` days have elapsed
    since it was first observed — whichever comes first. Fail-open: never
    raises; a partial/corrupt read degrades to "no reconciliation this
    pass" rather than crashing the caller.

    #878: the SAME pass that first flips a candidate to ``answered`` also
    computes its harness-measured verdict (:func:`_apply_verdict`); every
    LATER pass over an ``answered`` candidate whose verdict is still
    ``"inconclusive"`` re-checks it (:func:`_maybe_upgrade_inconclusive_verdict`)
    so a confirmed-usage signal that only arrives after day 0 can still
    resolve the verdict.
    """
    try:
        state_dir = Path(state_dir)
        now = now or datetime.now(timezone.utc)
        # One read per source: candidates, the status that says whether the
        # read succeeded, and the present-key set all come from the SAME
        # bytes — a transient read failure can no longer show up as "the file
        # was fine (status ok) but held nothing (no candidates)" and orphan
        # every present row. input_id_collisions: the strategist has reused
        # ids (live durable.json 2026-09-05: hyp-0021 carried 4 different
        # hypotheses, hyp-0022 three), so an id-keyed row can silently stand
        # for several entries.
        inputs, candidates, present, input_id_collisions = _read_inputs(state_dir)
        inputs_ok = all(status == "ok" for status in inputs.values())
        if all(status == "missing" for status in inputs.values()):
            return  # no hypothesis source at all: today's behaviour, no pass recorded

        lifecycle, lifecycle_status = _load_lifecycle_status(state_dir)
        if lifecycle_status == "corrupt":
            return  # never overwrite a sidecar we could not read (#1346 review)
        entries: dict[str, Any] = lifecycle.setdefault("entries", {})
        if not any(status == "ok" for status in inputs.values()):
            # The source exists but could not be read: nothing is evaluated,
            # nothing is orphaned, and the pass is recorded so the surface
            # shows inputs_unavailable instead of a silent no-op.
            lifecycle["updated_at"] = now.isoformat().replace("+00:00", "Z")
            lifecycle["last_pass"] = {
                "at": lifecycle["updated_at"],
                "inputs": inputs,
                "inputs_ok": False,
                "evaluated": 0,
                "orphaned_now": 0,
                "slug_keyed_candidates": 0,
                "input_id_collisions": 0,
            }
            _save_lifecycle(state_dir, lifecycle)
            return

        rows = _load_ledger_rows(state_dir)
        proposed_by_cycle: dict[str, dict[str, Any]] = {}
        outcome_by_cycle: dict[str, dict[str, Any]] = {}
        for row in rows:
            cid = row.get("cycle_id")
            if not cid:
                continue
            phase = row.get("phase")
            if phase == "proposed":
                proposed_by_cycle[cid] = row
            elif phase == "outcome":
                outcome_by_cycle[cid] = row

        touched_keys: set[str] = set()
        answered_keys: dict[str, str] = {}
        for cid, prow in proposed_by_cycle.items():
            ref = _serves_hypothesis_ref(str(prow.get("serves") or ""))
            explicit_ref = str(prow.get("hypothesis_ref") or "").strip()
            if not ref and not explicit_ref:
                continue
            for cand in candidates:
                if explicit_ref:
                    matches = explicit_ref == cand["key"]
                else:
                    matches = _ref_matches_candidate(ref, cand)
                if not matches:
                    continue
                touched_keys.add(cand["key"])
                outcome_row = outcome_by_cycle.get(cid)
                if outcome_row and outcome_row.get("outcome") == "success":
                    answered_keys[cand["key"]] = str(cid)

        now_iso = now.isoformat().replace("+00:00", "Z")
        for cand in candidates:
            key = cand["key"]
            entry = entries.get(key)
            if not isinstance(entry, dict):
                entry = {}
            entry.setdefault("status", "active")
            entry.setdefault("first_seen", now_iso)
            entry.setdefault("cycles_untouched", 0)
            entry.setdefault("title", cand["title"])
            # #1346: this key was in the inputs for this pass
            entry["last_evaluated"] = now_iso
            if entry.get("orphaned"):
                entry["reappeared_at"] = now_iso
            entry.pop("orphaned", None)
            entry.pop("orphaned_at", None)
            if cand.get("claim"):
                entry["claim_key"] = cand["claim"]

            if key in answered_keys and entry.get("status") != "answered":
                entry["status"] = "answered"
                entry["answered_evidence"] = answered_keys[key]
                entry["answered_at"] = now_iso
                # #878: compute + persist the harness-measured verdict the
                # SAME pass a hypothesis is first marked answered — no
                # separate hook into where cycle outcomes are recorded,
                # consistent with this module's existing lazy-reconciliation
                # design note above.
                _apply_verdict(state_dir, entry, key, answered_keys[key], now_iso)
            elif entry.get("status") == "answered" and entry.get("verdict") in (None, "inconclusive"):
                # #878 opus-review N1 fix: re-check on every LATER pass too —
                # see _maybe_upgrade_inconclusive_verdict's docstring for why
                # the confirmed-usage source needs this to ever fire.
                # #894: also catches legacy "answered" entries that predate
                # #878 entirely and so have NO verdict field at all (verdict
                # is None, not the string "inconclusive") — those never got
                # a first classify pass and would otherwise sit unevaluated
                # forever.
                _maybe_upgrade_inconclusive_verdict(state_dir, entry, key, now_iso)

            if entry.get("status") == "active":
                if key in touched_keys:
                    entry["cycles_untouched"] = 0
                    entry["last_touched"] = now_iso
                else:
                    entry["cycles_untouched"] = int(entry.get("cycles_untouched") or 0) + 1

                first_seen = _parse_ts(entry.get("first_seen")) or now
                age_days = (now - first_seen).total_seconds() / 86400.0
                if (
                    age_days >= STALE_AFTER_DAYS
                    or entry["cycles_untouched"] >= STALE_AFTER_UNTOUCHED_CYCLES
                ):
                    entry["status"] = "stale"
                    entry["stale_at"] = now_iso

            entries[key] = entry

        # #1346: a row whose key was absent from every input this pass is
        # not evaluated again and used to read exactly like an active row.
        # Mark it (never delete it) with the last pass that did evaluate it.
        # Only when every input was readable: an unreadable source is not
        # evidence that its hypotheses are gone. ``present`` is every key the
        # inputs carry (titled or not), from the same read as ``candidates``.
        orphaned_now = 0
        if inputs_ok:
            for key, entry in entries.items():
                if key in present or not isinstance(entry, dict):
                    continue
                if not entry.get("orphaned"):
                    entry["orphaned"] = True
                    entry["orphaned_at"] = now_iso
                    if not entry.get("last_evaluated"):
                        # legacy row (pre-#1346): best-known prior evaluation
                        entry["last_evaluated"] = (
                            entry.get("last_touched") or entry.get("stale_at")
                            or entry.get("answered_at") or entry.get("first_seen") or None
                        )
                    orphaned_now += 1
        lifecycle["entries"] = entries
        lifecycle["updated_at"] = now_iso
        lifecycle["last_pass"] = {
            "at": now_iso,
            "inputs": inputs,
            "inputs_ok": inputs_ok,
            "evaluated": len(present),
            "orphaned_now": orphaned_now,
            "slug_keyed_candidates": sum(1 for k in present if k.startswith("slug-")),
            "input_id_collisions": input_id_collisions,
        }
        _save_lifecycle(state_dir, lifecycle)
    except Exception:
        pass


def top_candidates(state_dir: Path, n: int = TOP_N) -> list[dict[str, str]]:
    """Top ``n`` still-``active`` candidates, durable-order then backlog-
    order, reconciling lifecycle state first. Fail-open: returns ``[]`` on
    any error."""
    try:
        state_dir = Path(state_dir)
        reconcile(state_dir)
        candidates = _all_candidates(state_dir)
        if not candidates:
            return []
        lifecycle = _load_lifecycle(state_dir)
        entries = lifecycle.get("entries", {})
        out: list[dict[str, str]] = []
        for cand in candidates:
            status = "active"
            stored = entries.get(cand["key"])
            if isinstance(stored, dict):
                status = str(stored.get("status") or "active")
            if status != "active":
                continue
            out.append(cand)
            if len(out) >= n:
                break
        return out
    except Exception:
        return []


def context_section(state_dir: Path) -> str:
    """Bounded ``## Hypothesis backlog (candidate value sources)`` body (no
    heading — the caller adds it), one ``- [<key>] <title>`` line per
    candidate. Fail-open: returns ``""`` on any error or when there are no
    active candidates, so the caller can omit the section entirely."""
    try:
        candidates = top_candidates(state_dir, TOP_N)
        if not candidates:
            return ""
        lines = [f"- [{cand['key']}] {cand['title']}" for cand in candidates]
        section = "\n".join(lines)
        if len(section) > MAX_SECTION_CHARS:
            section = section[:MAX_SECTION_CHARS]
        return section
    except Exception:
        return ""


