"""Hypotheses -> priorities reader (#751).

Gives the LLM proposer (``nanobot.runtime.llm_proposer``) a bounded,
fail-open read of the strategist's ``state_dir/hypotheses/durable.json``
(written by :func:`append_hypotheses` from the daily strategist run) as
candidate ``serves: hypothesis <id>`` targets, plus a small lifecycle
(active -> answered/stale, orphaned when absent — #1346) so the context
doesn't re-offer resolved or abandoned candidates forever.

Sources — ``durable.json`` only, since #1356. History of the others:
``research/hypotheses.json`` lost its writer with the planner (#916/#923,
removed as a source in #1219). ``hypotheses/backlog.json`` was #751's primary
source: first written by the planner's ``cycle_persist``, then (#913) by the
bridge's ``backlog_snapshot.write_backlog_snapshot`` at the end of every run
from the request queue minus handled markers. One request per cycle,
proposed in one bridge run and executed in the next, meant the file
alternated between one entry (the request the loop had just written for
itself) and none — never a backlog — and every transient entry minted a
``hypothesis-llm-proposer-cycle-*`` lifecycle row that #1346 then found
orphaned (82 of 100). Writer and reader retired together in #1356; the live
file is left inert on the host, read by nothing here.

Design note — why lifecycle state is NOT stored inside the source file: the
sources are regenerated by their own writers, so any status key added to an
entry would be wiped by the next write. This module owns a small sidecar,
``state_dir/hypotheses/lifecycle.json``, keyed by a stable candidate key
(the entry's ``hypothesis_id`` when present, else a slug of the title) that
it reads/writes exclusively — additive-only, never dropping unknown fields.

Everything here is fail-open: a missing/corrupt file, or any unexpected
shape, degrades to "no candidates" / "no lifecycle change" rather than
raising. Nothing here ever touches ``durable.json`` itself — it remains
owned by :func:`append_hypotheses`.

#878 (closing the hypothesis -> experiment -> verdict loop): ``reconcile``
now also computes a harness-MEASURED verdict (:mod:`hypothesis_verdict`) the
same pass it first marks a candidate ``answered``, persisting ``verdict``/
``verdict_evidence``/``verdict_at`` onto the SAME lifecycle entry.
:func:`supported_hypotheses` and :func:`lifecycle_counts` read the verdict
back out for, respectively, ``goal_review``'s evidence input and the
scorecard control-plane snapshot; :func:`has_in_flight_experiment` is the
read side of the "at most one active hypothesis experiment" rule
``demand._hypothesis_items`` enforces. See ``hypothesis_verdict``'s module
docstring for the full trust argument (verdict is steering, never a
verification gate).
"""
